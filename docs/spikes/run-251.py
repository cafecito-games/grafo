"""Local corpus experiment; raw responses stay outside the repository.

Usage: python3 docs/spikes/run-251.py /path/to/repository /path/to/results /path/to/local-cases.json
Build /tmp/grafo-investigate-spike first and complete `grafo index` separately.
Baseline uses the existing Find API and identical enrichment allocations; its
query terms are manually selected in advance, not generated by the prototype.
This measures retrieval and composition, not an agent/model experiment.
"""
import json
import os
import pathlib
import shlex
import statistics
import subprocess
import sys
import time

root, output, corpus = sys.argv[1:]
out = pathlib.Path(output)
out.mkdir(parents=True, exist_ok=True)
cases = json.loads(pathlib.Path(corpus).read_text())
summary = []
for case in cases:
    for mode in ["prototype", "baseline"]:
        samples = []
        for repeat in range(3):
            cmd = ["/tmp/grafo-investigate-spike", "-repo", root]
            if mode == "prototype":
                cmd += shlex.split(os.environ.get("SPIKE_ARGS", "")) + ["-path-prefix", case["scope"], case["query"]]
            else:
                cmd += ["-baseline", case["baseline"]]
            start = time.monotonic()
            result = subprocess.run(cmd, capture_output=True, check=True, timeout=40)
            elapsed = (time.monotonic() - start) * 1000
            data = json.loads(result.stdout)
            (out / f'{case["id"]}-{mode}-{repeat}.json').write_bytes(result.stdout)
            ranks = [i + 1 for i, c in enumerate(data["candidates"])
                     if (case.get("paths") or case.get("names"))
                     and (not case.get("paths") or c["node"]["location"]["path"] in case["paths"])
                     and (not case.get("names") or c["node"]["name"] in case["names"])]
            samples.append({"wall_ms": round(elapsed, 1), "bytes": len(result.stdout),
                            "rank": min(ranks) if ranks else None,
                            "empty": not data["candidates"], "truncated": data["truncated"]})
        row = {"case": case["id"], "mode": mode,
               "median_ms": round(statistics.median(s["wall_ms"] for s in samples), 1),
               "bytes": samples[-1]["bytes"], "rank": samples[-1]["rank"],
               "empty": samples[-1]["empty"], "truncated": samples[-1]["truncated"],
               "candidates": [c["node"]["qualified_name"] for c in data["candidates"]],
               "samples": samples}
        summary.append(row)
        print(json.dumps(row), flush=True)
(out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
